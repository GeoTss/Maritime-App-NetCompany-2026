/** The case id of a hard case. */
export const hardCaseId = (name: HardCaseName): string => `hard-${name}`;

async function attachmentOf(a: HardAttachment) {
  if (a.kind === "pdf-image") {
    return {
      filename: a.filename,
      contentType: "application/pdf",
      content: await buildImageOnlyPdf(),
    };
  }
  return { filename: a.filename, contentType: "text/html", content: a.html };
}

export async function renderHardCase(spec: HardCaseSpec): Promise<GoldenCase> {
  const id = hardCaseId(spec.name);
  const domain = spec.from.address.split("@")[1] ?? "example";
  const attachments = await Promise.all((spec.attachments ?? []).map(attachmentOf));
  return {
    truth: { id, tags: ["hard", spec.name, ...spec.tags], source: "hard", expected: spec.expected },
    mail: {
      from: spec.from,
      to: DESK,
      subject: spec.subject,
      date: new Date(spec.received),
      messageId: messageIdOf(id, domain),
      text: spec.text,
      ...(attachments.length > 0 ? { attachments } : {}),
    },
    transcription: spec.transcription,
    note: spec.tricky,
  };
}
